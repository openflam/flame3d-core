def _save_code(code: str, dataset_name: str | None) -> None:
    dname = dataset_name or "unknown"
    query_timestamp = datetime.datetime.now().strftime("%Y%m%d_%H%M%S_%f")
    
    out_dir = Path(__file__).parent / ".." / ".." / ".." / "benchmark" / "executed_code"
    out_dir.resolve().mkdir(parents=True, exist_ok=True)
    
    out_file = out_dir.resolve() / f"{dname}_{query_timestamp}.py"
    
    try:
        with open(out_file, "w") as f:
            f.write(code)
        os.chmod(out_file, 0o666)
    except Exception as e:
        print(f"Warning: Failed to save code to {out_file}: {e}")

def execute_python(code: str, dataset_name: str | None = None, save_code: bool = False) -> dict[str, Any]:
    """
    Execute a python program generated by the LLM in a sandbox.
    
    Args:
        code: The python code to execute.
        dataset_name: Dataset to run tools against.
        save_code: Whether to save the code to a file under outputs/{dataset_name}/queries/{query_timestamp}.py
        
    Returns:
        A dictionary containing 'output' (stdout) and 'error' (traceback if any).
    """
    # Set up the sandbox environment
    sandbox_globals = {
        "__builtins__": __builtins__,
        "np": np,
        "search_terms": functools.partial(search_terms, dataset_name=dataset_name),
        "get_distance": functools.partial(get_distance, dataset_name=dataset_name),
        "search_around_component": functools.partial(search_around_component, dataset_name=dataset_name),
        "get_component_info": functools.partial(get_component_info, dataset_name=dataset_name),
    }
    
    # Capture stdout
    stdout_capture = io.StringIO()
    error_msg = None
    
    try:
        with contextlib.redirect_stdout(stdout_capture):
            # We use exec to run the code.
            # We provide sandbox_globals as the globals and a new dict for locals
            # to avoid polluting the globals and to capture any variables created.
            exec(code, sandbox_globals, {})
    except Exception:
        error_msg = traceback.format_exc()
        
    if save_code:
        _save_code(code, dataset_name)
            
    return {
        "output": stdout_capture.getvalue(),
        "error": error_msg
    }

